export function traditional(text) {
  const converted = toTaiwan(text);
  for (const [draft, revised] of editorial) {
    if (converted.includes(draft)) return converted.replace(draft, revised).replace(pattern, term => terms[term]);
  }
  return converted.replace(pattern, term => terms[term]);
}
